use ply_launcher::code::reachable_lock_entries;

const LOCK: &str = r#"# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "a"
version = "0.1.0"
dependencies = [
 "b",
 "c 1.0.0",
]

[[package]]
name = "b"
version = "0.1.0"

[[package]]
name = "c"
version = "1.0.0"

[[package]]
name = "c"
version = "2.0.0"
checksum = "two"

[[package]]
name = "unrelated"
version = "0.1.0"
dependencies = [
 "c 2.0.0",
]
"#;

#[test]
fn the_runtime_lock_text_contains_the_requested_packages_and_their_dependencies_but_no_unrelated_packages()
 {
    let reached = reachable_lock_entries(LOCK, &["a"]);
    assert!(reached.contains("name = \"a\"") && reached.contains("name = \"b\""));
    assert!(reached.contains("version = \"1.0.0\""), "{reached}");
    assert!(!reached.contains("checksum = \"two\""), "{reached}");
    assert!(!reached.contains("unrelated"), "{reached}");
}
